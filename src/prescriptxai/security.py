"""Credentials and bounded, process-local sessions for the serving boundary."""

from __future__ import annotations

import hashlib
import os
import re
import secrets
from collections import deque
from dataclasses import dataclass
from threading import Lock
from time import monotonic
from typing import Literal
from urllib.parse import urlsplit

Role = Literal["operator", "admin"]
_ITERATIONS = 600_000
_LOGIN_WINDOW = 60
_IDLE_SECONDS = 300
_LIFETIME_SECONDS = 900
_DEFAULTS = ("admin", "operator", "password", "changeme", "prescriptxai")


def _password_digest(password: str, salt: bytes) -> bytes:
    return hashlib.pbkdf2_hmac("sha256", password.encode(), salt, _ITERATIONS)


def hash_password(password: str) -> str:
    """Generate a salted password verifier suitable for the process environment."""
    if not 15 <= len(password) <= 256 or password.casefold() in _DEFAULTS:
        raise ValueError("choose a non-default password of 15 to 256 characters")
    salt = secrets.token_bytes(16)
    return f"pbkdf2-sha256:{_ITERATIONS}:{salt.hex()}:{_password_digest(password, salt).hex()}"


@dataclass(frozen=True)
class PasswordVerifier:
    """Parsed password hash with a fixed, bounded work factor."""

    salt: bytes
    digest: bytes

    @classmethod
    def from_environment(cls, variable: str) -> PasswordVerifier:
        """Read one salted verifier and reject weak built-in credential values."""
        value = os.environ.get(variable, "")
        match = re.fullmatch(r"pbkdf2-sha256:600000:([a-f0-9]{32}):([a-f0-9]{64})", value)
        if match is None:
            raise ValueError(
                f"set {variable} to a verifier generated by prescriptxai hash-password"
            )
        verifier = cls(bytes.fromhex(match[1]), bytes.fromhex(match[2]))
        if any(verifier.matches(password) for password in _DEFAULTS):
            raise ValueError(f"{variable} uses a default password")
        return verifier

    def matches(self, password: str) -> bool:
        """Compare an entered password without exposing the stored digest."""
        return secrets.compare_digest(_password_digest(password, self.salt), self.digest)


@dataclass
class Session:
    """One opaque session bound to a role, deadlines and CSRF token."""

    role: Role
    expires: float
    idle_until: float
    csrf: str


def _token_key(token: str) -> bytes:
    return hashlib.sha256(token.encode()).digest()


class AuthStore:
    """Bound login attempts and keep token verifiers in process memory."""

    def __init__(self, origin: str, operator: PasswordVerifier, admin: PasswordVerifier) -> None:
        url = urlsplit(origin)
        if not url.hostname or origin != f"https://{url.netloc}" or url.username is not None:
            raise ValueError("PRESCRIPTXAI_AUTH_ORIGIN must be an exact HTTPS origin")
        if url.port is not None and not 1 <= url.port <= 65535:
            raise ValueError("PRESCRIPTXAI_AUTH_ORIGIN port is out of range")
        if operator.salt == admin.salt:
            raise ValueError("operator and admin password verifiers must use distinct salts")
        self.origin, self.host = origin, url.netloc.lower()
        self._operator, self._admin = operator, admin
        self._sessions: dict[bytes, Session] = {}
        self._attempts: deque[tuple[float, str]] = deque()
        self._lock = Lock()

    @classmethod
    def from_environment(cls) -> AuthStore:
        """Load serving credentials without modifying scientific configuration."""
        origin = os.environ.get("PRESCRIPTXAI_AUTH_ORIGIN", "")
        if not origin:
            raise ValueError("set PRESCRIPTXAI_AUTH_ORIGIN before starting authenticated service")
        return cls(
            origin,
            PasswordVerifier.from_environment("PRESCRIPTXAI_OPERATOR_PASSWORD_HASH"),
            PasswordVerifier.from_environment("PRESCRIPTXAI_ADMIN_PASSWORD_HASH"),
        )

    def admit_login(self, ip: str) -> bool:
        """Limit attempts per client and across all clients, including successful logins."""
        now = monotonic()
        with self._lock:
            while self._attempts and self._attempts[0][0] <= now - _LOGIN_WINDOW:
                self._attempts.popleft()
            if len(self._attempts) >= 64 or sum(peer == ip for _, peer in self._attempts) >= 6:
                return False
            self._attempts.append((now, ip))
            return True

    def authenticate(self, username: str, password: str) -> Role | None:
        """Verify credentials without distinguishing unknown users from wrong passwords."""
        verifier = self._admin if username == "admin" else self._operator
        if len(password) > 256 or not verifier.matches(password):
            return None
        if username == "operator":
            return "operator"
        return "admin" if username == "admin" else None

    def issue(self, role: Role) -> tuple[str, Session] | None:
        """Issue a random session or refuse when the active-session limit is reached."""
        now = monotonic()
        with self._lock:
            self._sessions = {
                key: value
                for key, value in self._sessions.items()
                if min(value.expires, value.idle_until) > now
            }
            if len(self._sessions) >= 256:
                return None
            token = secrets.token_urlsafe(32)
            session = Session(
                role, now + _LIFETIME_SECONDS, now + _IDLE_SECONDS, secrets.token_urlsafe(32)
            )
            self._sessions[_token_key(token)] = session
            return token, session

    def session(self, token: str, *, touch: bool = False) -> Session | None:
        """Check expiration and optionally refresh the inactivity window."""
        if len(token) != 43:
            return None
        now = monotonic()
        key = _token_key(token)
        with self._lock:
            session = self._sessions.get(key)
            if session is None:
                return None
            if min(session.expires, session.idle_until) <= now:
                self._sessions.pop(key)
                return None
            if touch:
                session.idle_until = min(now + _IDLE_SECONDS, session.expires)
            return session

    def revoke(self, token: str) -> None:
        """Invalidate a session immediately."""
        with self._lock:
            self._sessions.pop(_token_key(token), None)


def tls_files() -> tuple[str | None, str | None]:
    """Read the optional TLS certificate and key pair for a direct listener."""
    cert = os.environ.get("PRESCRIPTXAI_TLS_CERTFILE")
    key = os.environ.get("PRESCRIPTXAI_TLS_KEYFILE")
    if bool(cert) != bool(key):
        raise ValueError("set both PRESCRIPTXAI_TLS_CERTFILE and PRESCRIPTXAI_TLS_KEYFILE")
    return cert or None, key or None
